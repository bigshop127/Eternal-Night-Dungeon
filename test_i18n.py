def source_strings():
    out = []
    for f in FILES:
        tree = ast.parse(open(os.path.join(HERE, f), encoding="utf-8").read())
        docs = {id(n.body[0].value) for n in ast.walk(tree)
                if isinstance(n, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef))
                and n.body and isinstance(n.body[0], ast.Expr) and isinstance(getattr(n.body[0], "value", None), ast.Constant)}
        for n in ast.walk(tree):
            if isinstance(n, ast.Constant) and isinstance(n.value, str) and CJK.search(n.value) and id(n) not in docs:
                out.append(n.value)
    return out


def main():
    assert i18n.LANG == "en"
    bad = [(s, i18n.T(s)) for s in source_strings() + LOG_LINES if CJK.search(i18n.T(s))]
    for s, t in bad[:20]:
        print("  [FAIL]", s[:60], "→", t[:80])
    print(f"  {len(source_strings())} 段程式字串＋{len(LOG_LINES)} 行真實記錄，翻完還有中文的：{len(bad)}")
    ok = not bad and i18n.T("▶ 開始自動") == "▶ Start auto" and i18n.T("路線 第4段 右1：點右隊正前的寶箱").startswith("Route Seg 4 R1")
    print("✅ 全部通過" if ok else "❌ 有失敗")
    return 0 if ok else 1


